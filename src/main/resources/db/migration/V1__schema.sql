-- Yapi365 temel şema (PostgreSQL 16)

CREATE TABLE project (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    VARCHAR(30)  NOT NULL UNIQUE,
    name    VARCHAR(255) NOT NULL,
    active  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE app_role (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR(50)  NOT NULL UNIQUE,
    name  VARCHAR(255) NOT NULL
);

CREATE TABLE role_permission (
    role_id     BIGINT      NOT NULL REFERENCES app_role (id) ON DELETE CASCADE,
    permission  VARCHAR(60) NOT NULL,
    PRIMARY KEY (role_id, permission)
);

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    display_name   VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(255),
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE user_role (
    user_id  BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role_id  BIGINT NOT NULL REFERENCES app_role (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE user_project (
    user_id     BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    project_id  BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, project_id)
);

-- Envers: her değişiklik için kim / ne zaman
CREATE TABLE audit_revision (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rev_timestamp  BIGINT NOT NULL,
    username       VARCHAR(200)
);

CREATE TABLE document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT       NOT NULL REFERENCES project (id),
    folder_path      VARCHAR(255) NOT NULL,
    title            VARCHAR(255) NOT NULL,
    current_version  INTEGER      NOT NULL,
    CONSTRAINT uq_document UNIQUE (project_id, folder_path, title)
);

CREATE TABLE document_aud (
    id               BIGINT   NOT NULL,
    rev              BIGINT   NOT NULL REFERENCES audit_revision (id),
    revtype          SMALLINT,
    project_id       BIGINT,
    folder_path      VARCHAR(255),
    title            VARCHAR(255),
    current_version  INTEGER,
    PRIMARY KEY (id, rev)
);

CREATE TABLE document_version (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT        NOT NULL REFERENCES document (id),
    version_no     INTEGER       NOT NULL,
    file_name      VARCHAR(255)  NOT NULL,
    content_type   VARCHAR(255),
    size_bytes     BIGINT        NOT NULL,
    sha256         VARCHAR(64)   NOT NULL,
    storage_path   VARCHAR(255)  NOT NULL,
    uploaded_by    VARCHAR(255)  NOT NULL,
    uploaded_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    sync_status    VARCHAR(20)   NOT NULL,
    sync_attempts  INTEGER       NOT NULL DEFAULT 0,
    sync_error     VARCHAR(1000),
    graph_item_id  VARCHAR(255),
    web_url        VARCHAR(1000),
    CONSTRAINT uq_document_version UNIQUE (document_id, version_no)
);
CREATE INDEX ix_document_version_sync ON document_version (sync_status);

CREATE TABLE contract (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        BIGINT       NOT NULL REFERENCES project (id),
    type              VARCHAR(20)  NOT NULL,
    contract_no       VARCHAR(50)  NOT NULL,
    counterparty      VARCHAR(255) NOT NULL,
    title             VARCHAR(255) NOT NULL,
    start_date        DATE,
    end_date          DATE,
    amount            NUMERIC(18, 2),
    currency          VARCHAR(3),
    guarantee_amount  NUMERIC(18, 2),
    guarantee_expiry  DATE
);
CREATE INDEX ix_contract_project ON contract (project_id);
CREATE INDEX ix_contract_end ON contract (end_date);
CREATE INDEX ix_contract_guarantee ON contract (guarantee_expiry);

CREATE TABLE contract_aud (
    id                BIGINT NOT NULL,
    rev               BIGINT NOT NULL REFERENCES audit_revision (id),
    revtype           SMALLINT,
    project_id        BIGINT,
    type              VARCHAR(20),
    contract_no       VARCHAR(50),
    counterparty      VARCHAR(255),
    title             VARCHAR(255),
    start_date        DATE,
    end_date          DATE,
    amount            NUMERIC(18, 2),
    currency          VARCHAR(3),
    guarantee_amount  NUMERIC(18, 2),
    guarantee_expiry  DATE,
    PRIMARY KEY (id, rev)
);

CREATE TABLE mail_rule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255) NOT NULL,
    priority          INTEGER      NOT NULL,
    sender_contains   VARCHAR(255),
    subject_contains  VARCHAR(255),
    keywords          VARCHAR(255),
    action_type       VARCHAR(30)  NOT NULL,
    target_module     VARCHAR(20),
    target_folder     VARCHAR(255),
    notify_email      VARCHAR(255),
    active            BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE mail_rule_aud (
    id                BIGINT NOT NULL,
    rev               BIGINT NOT NULL REFERENCES audit_revision (id),
    revtype           SMALLINT,
    name              VARCHAR(255),
    priority          INTEGER,
    sender_contains   VARCHAR(255),
    subject_contains  VARCHAR(255),
    keywords          VARCHAR(255),
    action_type       VARCHAR(30),
    target_module     VARCHAR(20),
    target_folder     VARCHAR(255),
    notify_email      VARCHAR(255),
    active            BOOLEAN,
    PRIMARY KEY (id, rev)
);

CREATE TABLE mail_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    graph_message_id  VARCHAR(255) UNIQUE,
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    sender            VARCHAR(255) NOT NULL,
    subject           VARCHAR(500) NOT NULL,
    matched_rule      VARCHAR(255),
    classified_by     VARCHAR(10),
    action_result     VARCHAR(1000)
);
CREATE INDEX ix_mail_log_received ON mail_log (received_at);
